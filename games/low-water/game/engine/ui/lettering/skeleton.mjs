// The lettering's skeleton (the UI art lead's, 2026-10-21): every letter as the strokes a sign painter
// would make, in order and in the direction the brush travels, so a stroke's loaded start and dry end
// fall where a hand puts them. Units: 100 to the em, y up, the baseline at 0; caps 70, x-height 46,
// ascenders 76, descenders -24. Each glyph: { w: advance, s: [stroke, ...] }, a stroke a list of [x, y]
// points, smoothed by the rasteriser (Catmull-Rom). A stroke of two near points is a dot (a dab).
// Original letterforms, drawn for this game; no font was traced.
//   GLYPHS[ch] -> { w, s }     glyphFor(ch) -> the glyph, or a stand-in for a character not drawn

// points round an ellipse centred (cx, cy), from angle a0 to a1 in degrees (0 right, 90 up), n steps
export function arc(cx, cy, rx, ry, a0, a1, n = 0) {
  const k = n || Math.max(6, Math.round(Math.abs(a1 - a0) / 15)), out = [];
  for (let i = 0; i <= k; i++) { const a = ((a0 + ((a1 - a0) * i) / k) * Math.PI) / 180; out.push([+(cx + rx * Math.cos(a)).toFixed(2), +(cy + ry * Math.sin(a)).toFixed(2)]); }
  return out;
}
