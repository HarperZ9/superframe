// tools/capabilities.mjs: the medium-to-medium capability map, measured from the live registry and the type engine's
// router, written to CAPABILITIES.md. Re-run whenever an adapter lands:  node tools/capabilities.mjs
import { writeFileSync } from 'node:fs';
import { registry, techniques } from '../lib/registry.mjs';
import { conversionPath, convertible } from '../lib/graph.mjs';
import { route } from '../../typeengine/lib/adapters.mjs';

// Each medium as a port type (and, where one exists, the type engine property for it).
const MEDIA = {
  language: { type: 'text', prop: null, doc: 'typed or picked words' },
  numbers: { type: 'series', prop: 'data.series', doc: 'a list of values' },
  image: { type: 'raster', prop: 'surface.albedo', doc: 'a picture taken in or drawn' },
  art: { type: 'raster', prop: 'surface.albedo', doc: 'a picture made by a technique node', art: true },
  code: { type: 'text', prop: null, doc: 'source code as text', code: true },
  sound: { type: 'audio', prop: 'sound.pcm', doc: 'samples' },
  motion: { type: 'motion', prop: null, doc: 'frames with captions' },
};
const NEW = new Set(['story.mosaic', 'story.voice', 'language.explaincode', 'language.describesound', 'language.describepicture', 'language.numbers', 'motion.breathe', 'convert.text-series', 'convert.motion-raster', 'convert.motion-text', 'convert.raster-text', 'convert.audio-text']);
const ART_LANES = new Set(['image', 'type', 'matter', 'vector', 'field', 'motion']);

function viaNode(a, b) {
  // technique nodes that take something A converts into and give something that converts into B; prefer nodes whose
  // input is A's own type and whose output is B's own type
  const out = [];
  for (const n of techniques()) {
    if (n.kind === 'convert' || n.explore === false && !NEW.has(n.id)) continue;
    const ins = Object.values(n.inputs), req = ins.filter(s => !s.optional);
    const first = req[0] ?? ins[0]; if (!first) continue;
    if (req.length > 1) continue;
    if (!convertible(a.type, first.type)) continue;
    if (n.id === 'language.explaincode' && !a.code) continue;
    if (n.lane === 'language' && first.type !== a.type) continue;
    const outs = Object.values(n.outputs);
    if (!outs.some(t => convertible(t, b.type))) continue;
    if (b.art && !ART_LANES.has(n.lane)) continue;
    const steps = Math.min(...outs.map(t => conversionPath(t, b.type)?.length ?? 9)) + (conversionPath(a.type, first.type)?.length ?? 9);
    const exact = (first.type === a.type ? 2 : 0) + (outs.includes(b.type) ? 2 : 0) + (NEW.has(n.id) ? 1 : 0) - steps;
    out.push({ id: n.id, exact });
  }
  return out.sort((p, q) => q.exact - p.exact).slice(0, 3).map(o => o.id);
}

const rows = [], names = Object.keys(MEDIA);
for (const an of names) for (const bn of names) {
  if (an === bn) continue;
  const a = MEDIA[an], b = MEDIA[bn];
  const chain = a.code ? null : b.art ? null : conversionPath(a.type, b.type);
  // code reaches other media through its plain-words reading first; nothing in the engine writes code
  const nodes = b.code ? [] : a.code ? (bn === 'language' ? ['language.explaincode'] : ['language.explaincode', ...viaNode(MEDIA.language, b).slice(0, 2)]) : viaNode(a, b);
  const te = a.prop && b.prop ? route(a.prop, b.prop) : null;
  const status = b.code ? 'missing' : chain?.length || nodes.length ? 'works' : 'missing';
  rows.push({ from: an, to: bn, status, auto: chain ? chain.map(c => c.id.replace('convert.', '')).join(' > ') : '', nodes, typeengine: te ? te.map(x => `${x.from}>${x.to}`).join(', ') : (a.prop && b.prop ? 'no route' : 'n/a'), built: nodes.some(n => NEW.has(n)) || (chain ?? []).some(c => NEW.has(c.id)) });
}

const cell = r => (r.status === 'missing' ? 'missing' : r.auto ? 'auto' : r.from === 'code' ? 'two nodes' : 'node');
const L = ['<!-- writing-profile: research -->', '<!-- generated by tools/capabilities.mjs from the live registry; do not edit by hand -->', '# Capability map: medium to medium', '',
  `Measured ${new Date().toISOString().slice(0, 10)} from ${techniques().length} nodes and ${registry.size - techniques().length} converters, and from the type engine's \`route()\` (typeengine/lib/adapters.mjs).`, '',
  '- **auto**: the graph converts with no technique node, through a converter chain. Technique nodes for the same step are listed too.',
  '- **node**: one technique node (named below) makes the step, with converters inserted around it.',
  '- **two nodes**: code is first read into plain words (`language.explaincode`), then a language node takes over.',
  '- **missing**: no path in either system.',
  '- **built 2026-10-25**: the path uses a node or converter added for the transformation engine.', '',
  `| from \\ to | ${names.join(' | ')} |`, `|---|${names.map(() => '---').join('|')}|`,
  ...names.map(a => `| **${a}** | ${names.map(b => (a === b ? '' : cell(rows.find(r => r.from === a && r.to === b)))).join(' | ')} |`), '',
  '## Every path', '', '| From | To | Status | Automatic chain | Through a node | Type engine route | Built 2026-10-25 |', '|---|---|---|---|---|---|---|',
  ...rows.map(r => `| ${r.from} | ${r.to} | ${r.status} | ${r.auto || '-'} | ${r.nodes.map(n => '`' + n + '`').join(', ') || '-'} | ${r.typeengine} | ${r.built ? 'yes' : ''} |`), '',
  '## Notes', '',
  '- Language and code share the `text` port. Code reaches other media through `language.explaincode` first, so code is read as structure, and nothing runs it.',
  '- Art and image share the `raster` port. "Art" counts only paths through a technique node in a picture-making lane, because a converter alone does not make art.',
  '- The type engine routes between properties of a panel of light, and it has no language or motion-frame properties. Its routes cover numbers, image and sound among themselves; `lib/props.mjs` bridges them to ports.',
  '- Missing on purpose: anything to code. Writing a program from words, numbers or pictures needs a language model, and this engine stays local, deterministic and model-free.',
  '- Not checked here: whether each path makes something good. The map says a path runs; `TASTE.md` covers how good the results are.',
  '- Dropped: language to code. Writing a program from words needs a language model, and this engine stays local, deterministic and model-free.', ''];
writeFileSync(new URL('../CAPABILITIES.md', import.meta.url), L.join('\n'));
