// tools/gendocs.mjs: generate docs/NODES.md from the registry, so the reference can never lag the code.
//   node tools/gendocs.mjs
import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { ALL, techniques } from '../lib/registry.mjs';
import { TYPES } from '../lib/types.mjs';

const range = p => (p.type === 'number' || p.type === 'int' ? `${p.min} to ${p.max}` : p.type === 'enum' ? p.options.join(', ') : p.type === 'bool' ? 'true or false' : p.options?.length ? p.options.join(', ') : 'text');

export function docsMarkdown() {
  const lanes = [...new Set(techniques().map(n => n.lane))].sort();
  const L = ['<!-- generated by tools/gendocs.mjs; do not edit by hand -->', '# Superframe nodes', '',
    `${techniques().length} technique nodes in ${lanes.length} lanes, and ${ALL.length - techniques().length} converters. Port types are in the first table; every node follows.`, '',
    '## Port types', '', '| Type | Shape |', '|---|---|', ...Object.entries(TYPES).map(([k, t]) => `| \`${k}\` | ${t.doc} |`), ''];
  for (const lane of lanes) {
    L.push(`## Lane: ${lane}`, '');
    for (const n of techniques().filter(x => x.lane === lane)) {
      L.push(`### \`${n.id}\`: ${n.title}`, '');
      if (n.doc) L.push(n.doc, '');
      L.push(`Source: \`${n.source}\`. Runtime: ${n.runtime.join(', ')}. Fields: ${n.domains.join(', ') || 'none'}.${n.edge ? ` Perception trick (${n.edge.persuasion}); must reach an output with ${n.edge.counterpart.join(' or ')}.` : ''}`, '');
      const ins = Object.entries(n.inputs), outs = Object.entries(n.outputs);
      L.push(`Inputs: ${ins.length ? ins.map(([k, s]) => `\`${k}\` ${s.type}${s.optional ? ' (optional)' : ''}`).join(', ') : 'none'}. Outputs: ${outs.map(([k, t]) => `\`${k}\` ${t}`).join(', ')}.`, '');
      const ps = Object.entries(n.params);
      if (ps.length) { L.push('| Parameter | Range | Default | Unit |', '|---|---|---|---|'); for (const [k, p] of ps) L.push(`| \`${k}\` | ${range(p)} | ${p.default} | ${p.unit || (p.doc ?? '')} |`); L.push(''); }
    }
  }
  L.push('## Converters', '', 'Inserted automatically by the graph where two port types differ (shortest chain).', '', '| Converter | From | To |', '|---|---|---|');
  for (const c of ALL.filter(x => x.kind === 'convert')) L.push(`| \`${c.id}\` | ${c.inputs.in.type} | ${c.outputs.out} |`);
  return L.join('\n') + '\n';
}

export function writeDocs() {
  const f = fileURLToPath(new URL('../docs/NODES.md', import.meta.url));
  mkdirSync(fileURLToPath(new URL('../docs/', import.meta.url)), { recursive: true });
  writeFileSync(f, docsMarkdown());
  return f;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) console.log(writeDocs());
