// tools/site-modules.mjs: add an adapter-plan column to the site module inventory (read from origin/main by a sweep)
// and write SITE-MODULES.md. Plans follow the runtime code; modules already adapted name their node.
//   node tools/site-modules.mjs <sweep.md>
import { readFileSync, writeFileSync } from 'node:fs';
const ADAPTED = {
  'retro-engine.js': 'adapted: `site.retro`', 'weave-engine.js': 'adapted: `site.loom`', 'plot-maps.js': 'adapted: `site.terrain`, `site.ridgelines`',
  'fractal-formula-cpu.js': 'adapted: `site.fractal`', 'sound.mjs': 'adapted: `convert.field-audio`, `site.seedsound`, `site.oscilloscope`',
  'midi-writer.js': 'adapted: MIDI export (`lib/export.mjs`)', 'relief-stl.js': 'adapted: STL export (`lib/export.mjs`)', 'contracts.mjs': 'used: PCM and WAV helpers',
};
const plan = (file, runtime, role) => {
  const base = file.replace(/\s*\[.*$/, '').split('/').pop().trim();
  if (ADAPTED[base]) return ADAPTED[base];
  const r = runtime.trim()[0];
  if (/page glue/.test(role)) return 'none: page driver (P5 if a pure core is split out)';
  if (/utility/.test(role)) return 'library: imported by adapters when needed';
  return { N: 'P1: wrap now (pure, Node)', C: /recording/.test(runtime) ? 'P2: recording 2D context' : 'P2: pixel 2D context (ImageData)', G: 'P3: CPU twin or headless GL', A: 'P4: offline audio shim', D: 'P5: extract the pure core' }[r] ?? 'review';
};
const src = readFileSync(process.argv[2], 'utf8').split('\n'), out = [];
for (const line of src) {
  if (/^\| file \|/.test(line)) { out.push(line.replace(/\|\s*$/, '| adapter plan |')); continue; }
  if (/^\|---/.test(line)) { out.push(line.replace(/\|\s*$/, '|---|')); continue; }
  const m = line.match(/^\| (.+?) \| .* \| (.*?) \| ([^|]*?) \|\s*$/);
  if (m && /^\| /.test(line)) { out.push(line.replace(/\|\s*$/, `| ${plan(m[1], m[2], m[3])} |`)); continue; }
  out.push(line);
}
const head = `<!-- writing-profile: research -->
<!-- generated by tools/site-modules.mjs from a module sweep of HarperZ9.github.io system/ at origin/main 3ca6529 -->
# Site modules and their adapter plans

Every first-party source module in the site's \`system/\` folder at origin/main 3ca6529, with an adapter plan for each. The superframe adapters cover the generators; page drivers and utilities are listed so nothing is missed. \`INVENTORY.md\` covers the other 13 sources.

**Plans, by runtime:**
- **adapted:** a superframe node or export path calls the module today.
- **P1, pure (N):** wrap it in a \`defineNode\` now. It imports in Node, and many site tests already import it headless.
- **P2, 2D canvas (C):** run it against a software 2D context in \`lib/canvas2d.mjs\` (planned). A recording context is enough for modules marked "recording"; modules that read pixels back need an ImageData buffer.
- **P3, WebGL or WebGPU (G):** use the CPU twin where one exists (the fractal family has them). Otherwise use headless GL in an R&D worker, and keep the shader as the reference.
- **P4, WebAudio (A):** an offline audio shim covering the nodes these use: oscillator, gain, biquad, buffer source and worklet. The sound engine needs the same shim (INVENTORY section 9).
- **P5, page driver (D):** split the pure core out of the page. Then the core gets a node, and the page stays a driver.

**For the type engine (typeengine):**
- The old font studio is \`type-forge/\`, \`typeface.js\`, \`font-catalog.mjs\`, \`font-specimen.js\`, \`studio-type.js\` and the \`type\` media-engine plugin.
- Its generator cores are pure and tested in Node:
  - \`type-forge/forge.mjs\` (Zain Mint parametric outlines);
  - \`type-forge/ttf.mjs\` (TrueType writer);
  - \`typeface.js\` (seed-authored axes).
- They are P1, and are the natural first adapters for the font studio's successor.
- The superframe \`type.forge\` node uses the newer house forge (typeface). Both can sit side by side as two type sources.

`;
writeFileSync(new URL('../SITE-MODULES.md', import.meta.url), head + out.slice(out.findIndex(l => /^\*\*Not counted|^## Top level/.test(l))).join('\n'));
const plans = out.filter(l => /^\| [^f-]/.test(l) || /^\| f[^i]/.test(l)).map(l => l.split('|').at(-2).trim().split(':')[0]);
const c = {}; for (const p of plans) c[p] = (c[p] ?? 0) + 1; console.log(c);
