// wordmark-plates.mjs: measure the stratum palettes for the CMMNS strata direction from reference photographs, with
// the study plates' palette method (lib/study/palette.mjs: weighted k-means in CIELAB). Only measured colours leave
// this step; no reference pixel is copied into the mark. Writes lib/wordmark/strata-plates.mjs with each source's
// file, SHA-256, decoder and swatches, so the strata render reproduces without the references on disk.
//   node tools/wordmark-plates.mjs
// References: four Poly Haven CC0 textures, listed in REFS below. They are not in this repository: save each as
// <id>.jpg in a folder and name that folder in WORDMARK_PLATES (default out/wordmark-plates).
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { loadSubject } from '../lib/study/load.mjs';
import { palette, PALETTE_METHOD } from '../lib/study/palette.mjs';

const here = dirname(fileURLToPath(import.meta.url)), IMG = process.env.WORDMARK_PLATES ?? join(here, '../../out/wordmark-plates');
export const REFS = [
  { id: 'clay-floor', url: 'https://polyhaven.com/a/clay_floor_001', licence: 'CC0' },
  { id: 'clay-plaster', url: 'https://polyhaven.com/a/clay_plaster', licence: 'CC0' },
  { id: 'concrete-layers', url: 'https://polyhaven.com/a/concrete_layers_02', licence: 'CC0' },
  { id: 'hessian', url: 'https://polyhaven.com/a/hessian_230', licence: 'CC0' },
];

const plates = REFS.map(r => {
  const S = loadSubject(join(IMG, `${r.id}.jpg`)), P = palette(S, { k: 6, seed: `cmmns-strata/${r.id}` });
  console.log(r.id, S.w, S.h, P.swatches.map(s => `${s.hex} ${(100 * s.share).toFixed(1)}%`).join('  '));
  return { ...r, file: S.file, sha256: S.sha256, decoder: S.decoder, size: [S.w, S.h], swatches: P.swatches.map(s => ({ hex: s.hex, L: s.L, C: s.C, h: s.h, share: +s.share.toFixed(4) })) };
});
const body = `// Generated by tools/wordmark-plates.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.\n// Method: ${PALETTE_METHOD.method}.\nexport const PLATES = [\n${plates.map(p => ' ' + JSON.stringify(p)).join(',\n')},\n];\n`;
writeFileSync(join(here, '../lib/wordmark/strata-plates.mjs'), body);
console.log('wrote lib/wordmark/strata-plates.mjs');
