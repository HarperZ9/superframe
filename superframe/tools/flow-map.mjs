// tools/flow-map.mjs: writes FLOW-MAP.md, every registered node mapped into the medium. A node enters FLOW through
// what it makes: each output port type pours as the additives lib/medium/ports.mjs names. Generated, so the map
// cannot lag the registry.
//   node tools/flow-map.mjs
import { writeFileSync } from 'node:fs';
import { techniques } from '../lib/registry.mjs';

const POURS = {
  text: 'text: words as ink that sinks and dissolves, the words kept in the log',
  glyphs: 'text: as text',
  raster: 'form: a picture carried by the flow (rigid, stretch or dissolve)',
  motion: 'form: its middle frame, as a raster',
  vector: 'form: drawn lines, rasterised',
  field: 'form: a tone field as ink of that shape (or heat or salt)',
  particles: 'tiles: grains poured as sediment',
  audio: 'sound: the strongest pitch picks a standing mode (one shape among isospectral choices)',
  series: 'data: drives the amount of the additive before it',
  events: 'ink: drops at their times, coloured by pitch',
  material: 'sugar, turbulence, oil, tiles: from the material core',
  distribution: 'turbulence: by its spread (by analogy)',
  score: 'turbulence: in proportion to a missed target (by analogy)',
  time: 'clock: the tank is read at time.t',
};

const nodes = techniques().slice().sort((a, b) => a.lane.localeCompare(b.lane) || a.id.localeCompare(b.id));
const byType = {};
for (const n of nodes) for (const t of new Set(Object.values(n.outputs))) (byType[t] ??= []).push(n.id);
const lines = [
  '# FLOW map: every node in the medium',
  '',
  `Generated by \`node tools/flow-map.mjs\` from the registry: ${nodes.length} nodes. A node pours into the medium through its outputs; the rule for each port type lives in \`lib/medium/ports.mjs\`. FLOW.md explains the model.`,
  '',
  '## By port type',
  '',
  '| Port type | Nodes | Pours as |',
  '|---|---|---|',
  ...Object.entries(byType).sort((a, b) => b[1].length - a[1].length).map(([t, ids]) => `| ${t} | ${ids.length} | ${POURS[t] ?? 'no rule yet'} |`),
  '',
  '## Every node',
  '',
  '| Lane | Node | Outputs | Enters the medium as |',
  '|---|---|---|---|',
  ...nodes.map(n => { const outs = [...new Set(Object.values(n.outputs))]; return `| ${n.lane} | \`${n.id}\` | ${outs.join(', ')} | ${outs.map(t => (POURS[t] ?? 'no rule yet').split(':')[0]).join(', ')} |`; }),
  '',
];
writeFileSync(new URL('../FLOW-MAP.md', import.meta.url), lines.join('\n'));
console.log(`FLOW-MAP.md: ${nodes.length} nodes, ${Object.keys(byType).length} port types, ${Object.keys(byType).filter(t => !POURS[t]).length} without a rule`);
