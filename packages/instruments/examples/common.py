"""Shared helpers for the worked examples: one tool row, one gate, one stage, all in the schema's shape.

Each example reads its instrument record (../records/ID.json): the name, the summary and the stage-1 assumptions
are written once there, and the diagram package's CAD model reads the same record.
"""
import importlib.util
import json
from pathlib import Path

RECORDS = Path(__file__).resolve().parent.parent / "records"
_CONSTANTS = Path(__file__).resolve().parents[2] / "measured" / "generated" / "constants.py"


def _constants():
    """CODATA 2022 values generated by packages/measured (loaded by path, so no bare 'constants' on sys.path)."""
    spec = importlib.util.spec_from_file_location("measured_constants", _CONSTANTS)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


K = _constants()


def record(instrument_id):
    return json.loads((RECORDS / f"{instrument_id}.json").read_text(encoding="utf-8"))


def walls(rec):
    """Stage-1 wall assumptions in the stage schema's shape (the optional flag and door belong to the CAD spec sheet)."""
    return [{"assumption": a["assumption"], "how_checked": a["how_checked"], "if_broken": a["if_broken"]} for a in rec["assumptions"]]


def tool(name, role, licence, ours=False, lineage=None):
    t = {"name": name, "role": role, "licence": licence, "ours": ours}
    if lineage:
        t["lineage"] = lineage
    return t


def gate(condition, metric, op, threshold, verdict="open", measured=None, evidence=None):
    g = {"condition": condition, "metric": metric, "op": op, "threshold": threshold, "verdict": verdict}
    if measured is not None:
        g["measured"] = measured
    if evidence is not None:
        g["evidence"] = evidence
    return g


def stage(num, key, status, inputs, outputs, g, tools, spec, does_not_prove, notes=None):
    s = {"stage": num, "key": key, "status": status, "inputs": inputs, "outputs": outputs, "gate": g,
         "tools": tools, "spec": spec, "does_not_prove": does_not_prove}
    if notes:
        s["notes"] = notes
    return s


PY = tool("Python 3.12 and NumPy", "simulation and analysis", "PSF-2.0 and BSD-3-Clause", False,
          "NumPy: Oliphant (2006), from Numeric (Hugunin, 1995)")
STUDYRUN = tool("studyrun", "preregistration lock, controls, verdicts", "ours", True,
                "flywheel harness/studyrun")
BUS = tool("every-dimension bus.py", "receipt events on the measurement bus", "ours", True,
           "extends project-telos.measurement-bus/v1")
PERCEIVE = tool("tools/perceive", "perceptual bridge for the returned quantity", "ours", True,
                "registry.js bridges: heat, sound, polarisation")
KICAD = tool("KiCad 9", "schematic, PCB, ERC and DRC, BOM export", "GPL-3.0-or-later", False,
             "Jean-Pierre Charras (1992); CERN support from 2013 (from memory, moderate)")
NGSPICE = tool("ngspice", "noise and AC analysis of the front end", "BSD-3-Clause (modified BSD; from memory, moderate)",
               False, "Berkeley SPICE (Nagel and Pederson, 1973) through SPICE3f5")
CHECKS = tool("CHECKS.json", "named check techniques the stage uses", "ours", True,
              "the author's checks catalogue")
