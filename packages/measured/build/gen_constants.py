"""Generate the physical-constants modules every package imports, from data/codata2022.json.

    python packages/measured/build/gen_constants.py           write generated/constants.{py,js,json}
    python packages/measured/build/gen_constants.py --check   exit 1 when a generated file is stale

The generated files are data (CODATA 2022, a US Government work) and carry CC0-1.0, so FSL and AGPL
packages can both import them. tests/test_constants.py fails when a package keeps a hand copy.
"""
import json
import math
import sys
from pathlib import Path

PKG = Path(__file__).resolve().parent.parent
OUT = PKG / "generated"
NAMES = {  # short name: CODATA quantity
    "c": "speed of light in vacuum", "h": "Planck constant", "hbar": "reduced Planck constant",
    "kB": "Boltzmann constant", "e": "elementary charge", "eps0": "vacuum electric permittivity",
    "mu0": "vacuum mag. permeability", "NA": "Avogadro constant", "sigma": "Stefan-Boltzmann constant",
    "wienB": "Wien wavelength displacement law constant", "me": "electron mass", "u": "atomic mass constant",
}
HEAD = "SPDX-FileCopyrightText: 2026 Zain Dana Harper\nSPDX-License-Identifier: CC0-1.0\nGenerated by packages/measured/build/gen_constants.py from data/codata2022.json. Do not edit."


def table():
    rows = {r["quantity"]: r for r in json.loads((PKG / "data" / "codata2022.json").read_text(encoding="utf-8"))["rows"]}
    out = {}
    for short, quantity in NAMES.items():
        r = rows[quantity]
        out[short] = {"value": r["value"], "unit": r["unit"], "uncertainty": r["uncertainty"], "exact": r["exact"],
                      "quantity": quantity}
    out["ke"] = {"value": 1 / (4 * math.pi * out["eps0"]["value"]), "unit": "N m^2 C^-2", "uncertainty": None,
                 "exact": False, "quantity": "Coulomb constant, derived as 1/(4 pi eps0)"}
    return out


def render(t):
    py = "\n".join("# " + line for line in HEAD.splitlines()) + '\n"""CODATA 2022 constants (SI)."""\n'
    py += "".join(f"{k} = {v['value']!r}  # {v['unit']}; {v['quantity']}\n" for k, v in t.items())
    js = "\n".join("// " + line for line in HEAD.splitlines()) + "\n"
    js += "// CODATA 2022 constants (SI). CommonJS, and window.MeasuredConstants for classic scripts.\n"
    js += "(function (g) {\n  \"use strict\";\n  const C = Object.freeze({\n"
    js += "".join(f"    {k}: {v['value']!r},\n" for k, v in t.items())
    js += "  });\n  if (typeof module !== \"undefined\" && module.exports) module.exports = C;\n"
    js += "  else g.MeasuredConstants = C;\n})(typeof globalThis !== \"undefined\" ? globalThis : this);\n"
    data = json.dumps({"licence": "CC0-1.0", "source": "data/codata2022.json", "constants": t}, indent=1) + "\n"
    return {"constants.py": py, "constants.js": js, "constants.json": data}


def main(argv):
    files = render(table())
    if "--check" in argv:
        stale = [n for n, text in files.items() if not (OUT / n).is_file() or (OUT / n).read_text(encoding="utf-8") != text]
        for n in stale:
            print(f"stale: generated/{n}")
        return 1 if stale else 0
    OUT.mkdir(exist_ok=True)
    for n, text in files.items():
        (OUT / n).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote generated/{n}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
