"""Write the data perceive reads, from the sources that already exist. Stdlib only.

    python -I page/make_data.py

- src/cmf.js: CIE 1931 2-degree colour-matching functions, 380 to 780 nm at 5 nm, read from
  packages/materials/data/cie/CIE_xyz_1931_2deg.csv (CIE, CC BY-SA 4.0, DOI 10.25039/CIE.DS.xvudnb9b).
- data/materials-nk.json: n and k spectra of a few materials from packages/materials/data/materials.json.
- data/rings.json: the ring-channel composite series (years, ring z-scores, climate z-scores) from
  the private ring-channel study's rings.data.json, named by RINGS_DATA.
"""
import os
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PKGS = Path(__file__).resolve().parents[2]
CIE = PKGS / "materials" / "data" / "cie" / "CIE_xyz_1931_2deg.csv"
MAT = PKGS / "materials" / "data" / "materials.json"
RINGS = Path(os.environ.get("RINGS_DATA", "rings.data.json"))  # the private ring-channel study
PICK = ["gold", "silver", "copper", "aluminium", "iron", "silicon", "germanium", "gallium_arsenide",
        "water", "diamond", "bk7", "bismuth", "chromium", "titanium"]


def cmf():
    rows = {}
    with open(CIE, newline="", encoding="utf-8") as f:
        for r in csv.reader(f):
            if r and r[0].strip():
                rows[int(float(r[0]))] = [float(v) for v in r[1:]]
    table = [rows[w] for w in range(380, 781, 5)]
    body = ",".join("[%s]" % ",".join("%.6g" % v for v in t) for t in table)
    (ROOT / "src" / "cmf.js").write_text(
        "/* perceive/cmf: CIE 1931 2-degree colour-matching functions, 380 to 780 nm in 5 nm steps.\n"
        "   Data: International Commission on Illumination (CIE), CIE 018:2019 Table 6, DOI 10.25039/CIE.DS.xvudnb9b,\n"
        "   licensed CC BY-SA 4.0. Generated by page/make_data.py from the copy in tools/materials/data/cie. */\n"
        "(function (g) {\n  \"use strict\";\n  const P = (g.Perceive = g.Perceive || {});\n"
        "  P.CMF = { start: 380, step: 5, xyz: [" + body + "] };\n"
        "  if (typeof module !== \"undefined\" && module.exports) module.exports = P;\n"
        "})(typeof globalThis !== \"undefined\" ? globalThis : this);\n", encoding="utf-8")


def materials():
    d = json.loads(MAT.read_text(encoding="utf-8"))
    out = {"grid_nm": d["grid_nm"], "source": "packages/materials/data/materials.json", "materials": []}
    for m in d["materials"]:
        o = m.get("optics") or {}
        if m["id"] in PICK and isinstance(o.get("n"), dict) and isinstance(o.get("k"), dict):
            out["materials"].append({"id": m["id"], "name": m["name"], "n": o["n"]["value"], "k": o["k"]["value"],
                                     "source": o["n"].get("source", "")})
    (ROOT / "data" / "materials-nk.json").write_text(json.dumps(out), encoding="utf-8")
    return len(out["materials"])


def rings():
    d = json.loads(RINGS.read_text(encoding="utf-8"))["comp"]
    out = {"source": str(RINGS).replace("\\", "/"), "years": d["years"], "ring": d["z"], "climate": d["T"]}
    (ROOT / "data" / "rings.json").write_text(json.dumps(out), encoding="utf-8")
    return len(d["years"])


if __name__ == "__main__":
    (ROOT / "data").mkdir(exist_ok=True)
    cmf()
    print("materials", materials(), "rings years", rings())
