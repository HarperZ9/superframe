"""Generators that move space, from raw geometry only (no source image is reused).

hyperbolic(p, q)   a {p, q} tiling of the Poincare disk (p-gons, q meeting at each vertex; needs
                   1/p + 1/q < 1/2), drawn by folding each pixel into the fundamental triangle with
                   reflections in its three sides (two lines through the centre and one geodesic
                   circle). The parity of the fold count colours the tiles, and the distance to the
                   geodesic side draws the edges.
droste(...)        the log-polar conformal map behind a Droste spiral. Source: a field invariant under
                   scaling by s (nested squares). In w = log z the source is periodic under the lattice
                   generated by log s and 2 pi i; the map w -> w / beta with beta = 2 pi i / (2 pi i + log s)
                   turns one turn around the centre into one step of scale, so the output is single
                   valued and self-similar under z -> z * exp(beta log s) (scale and rotation together).
metamorphosis(...) a tessellation that changes continuously along x, so position stands for time:
                   a p4 field at the left and a p6 field at the right, blended by a smoothstep weight
                   before one contrast map, so tile contours deform from one tiling into the other.
"""
import numpy as np


def _circle_through_side(p, q):
    """Geodesic side of the fundamental triangle with angles pi/p at the centre, pi/q, pi/2."""
    a, b = np.pi / p, np.pi / q
    # distance from the centre to the triangle's right-angle vertex on the x axis, in the disk model
    ch = np.cos(b) / np.sin(a)          # cosh of hyperbolic distance to the edge midpoint
    d = np.sqrt((ch - 1) / (ch + 1))    # Euclidean radius in the Poincare disk
    # geodesic perpendicular to the x axis at x = d: a circle orthogonal to the unit circle
    cx = (1 + d * d) / (2 * d)
    r = np.sqrt(cx * cx - 1)
    return cx, r


def hyperbolic(p=7, q=3, size=512, max_iter=60):
    if 1 / p + 1 / q >= 0.5:
        raise ValueError("{p,q} must satisfy 1/p + 1/q < 1/2 for the hyperbolic plane")
    cx, r = _circle_through_side(p, q)
    y, x = (np.mgrid[:size, :size] - (size - 1) / 2) / (size / 2 * 0.995)
    z = x + 1j * y
    inside = np.abs(z) < 1
    w = z.copy()
    flips = np.zeros(z.shape, int)
    ang = np.pi / p
    for _ in range(max_iter):
        changed = np.zeros(z.shape, bool)
        # side 1: the x axis (reflect if below)
        m = inside & (w.imag < 0)
        w[m] = np.conj(w[m]); flips[m] += 1; changed |= m
        # side 2: the line at angle pi/p (reflect if above it)
        rot = np.exp(-1j * ang)
        m = inside & ((w * rot).imag > 0)
        w[m] = (np.conj(w[m] * rot)) / rot; flips[m] += 1; changed |= m
        # side 3: the geodesic circle (invert if inside it)
        m = inside & (np.abs(w - cx) < r)
        w[m] = cx + r * r / np.conj(w[m] - cx); flips[m] += 1; changed |= m
        if not changed.any():
            break
    edge = np.abs(np.abs(w - cx) - r) / r
    tile = flips % 2
    img = np.where(inside, 0.25 + 0.5 * tile, 1.0)
    img = np.where(inside & (edge < 0.02), 0.05, img)
    return img, {"flips": flips, "inside": inside, "folded": w, "cx": cx, "r": r}


def nested_squares(z, s=4.0):
    """Source field invariant under z -> s z: square rings in log-scale."""
    m = np.maximum(np.abs(z.real), np.abs(z.imag)) + 1e-12
    u = np.log(m) / np.log(s)
    ring = np.mod(u, 1.0)
    ang = np.angle(z)
    return 0.5 + 0.3 * np.sign(np.sin(2 * np.pi * ring * 2)) + 0.15 * np.cos(4 * ang) * (ring > 0.5)


def droste_beta(s):
    return 2j * np.pi / (2j * np.pi + np.log(s))


def droste(size=512, s=4.0, field=nested_squares):
    beta = droste_beta(s)
    y, x = (np.mgrid[:size, :size] - (size - 1) / 2) / (size / 2)
    z = x + 1j * y + 1e-9
    wsrc = np.log(z) / beta
    return field(np.exp(wsrc), s), {"beta": beta, "step": np.exp(beta * np.log(s))}


def metamorphosis(width=1024, height=256, cell=40, seed=0, a="p4", b="p6"):
    """Two periodic fields (groups a and b, lattices anchored at the top-left pixel) blended by a
    smoothstep weight along x, then passed through one odd contrast map, so the tile contours deform
    continuously from one tessellation into the other: position stands for time."""
    from .wallpaper import periodic_field
    Fa = periodic_field(a, width, height, cell, seed)
    Fb = periodic_field(b, width, height, cell, seed + 1)
    Fa, Fb = (Fa - Fa.mean()) / Fa.std(), (Fb - Fb.mean()) / Fb.std()
    t = np.linspace(0, 1, width)[None, :]
    w = t * t * (3 - 2 * t)
    out = np.tanh(1.5 * ((1 - w) * Fa + w * Fb))
    return (out - out.min()) / (np.ptp(out) + 1e-12)
