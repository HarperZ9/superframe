"""The Drude relation: why a good conductor is a mirror.

Free electrons of density n_e give a plasma frequency wp^2 = n_e e^2 / (eps0 m).
The DC conductivity sigma = n_e e^2 tau / m fixes the collision time tau. The same
electrons set the optical permittivity

    eps(w) = 1 - wp^2 / (w^2 + i w / tau)

and N = n + ik = sqrt(eps). Below wp the real part of eps is negative, k is large
and the Fresnel reflectance approaches 1: metallic reflection. Conductivity and
metallic appearance are one law seen at two frequencies.
"""
import cmath
import importlib.util
import math
import sys
from pathlib import Path


def _measured_constants():
    """CODATA 2022 constants generated by packages/measured/build/gen_constants.py, loaded by file path
    under a unique module name (the bare name "constants" is taken by build/constants.py)."""
    name = "measured_generated_constants"
    if name not in sys.modules:
        path = Path(__file__).resolve().parents[2] / "measured" / "generated" / "constants.py"
        spec = importlib.util.spec_from_file_location(name, path)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        sys.modules[name] = mod
    return sys.modules[name]


_K = _measured_constants()
E = _K.e        # C, exact (SI 2019)
ME = _K.me      # kg, CODATA 2022
EPS0 = _K.eps0  # F/m, CODATA 2022
NA = _K.NA      # 1/mol, exact (SI 2019)
C = _K.c        # m/s, exact


def electron_density(density_kg_m3, molar_mass_kg_mol, valence):
    return valence * density_kg_m3 * NA / molar_mass_kg_mol


def plasma_frequency(n_e):
    return math.sqrt(n_e * E * E / (EPS0 * ME))


def tau_from_sigma(sigma, n_e):
    return sigma * ME / (n_e * E * E)


def permittivity(wavelength_nm, sigma, n_e):
    w = 2 * math.pi * C / (wavelength_nm * 1e-9)
    wp = plasma_frequency(n_e)
    tau = tau_from_sigma(sigma, n_e)
    return 1 - wp * wp / (w * w + 1j * w / tau)


def nk(wavelength_nm, sigma, n_e):
    N = cmath.sqrt(permittivity(wavelength_nm, sigma, n_e))
    if N.imag < 0:
        N = -N
    return N.real, N.imag


def hagen_rubens_k(wavelength_nm, sigma):
    """Low-frequency limit (w tau << 1): n = k = sqrt(sigma / (2 eps0 w))."""
    w = 2 * math.pi * C / (wavelength_nm * 1e-9)
    return math.sqrt(sigma / (2 * EPS0 * w))


# Drude-Lorentz: the free electrons plus a few bound-electron (interband) oscillators.
# Photon energy in eV: E = HC_EV_NM / wavelength_nm.
#
#     eps(E) = eps_inf - Ep^2 / (E^2 + i G E) + sum_j A_j / (E_j^2 - E^2 - i G_j E)
#
# Ep is the free-electron plasma energy, G its damping, and each oscillator j has a
# strength A_j (eV^2), a centre E_j and a width G_j. In gold and copper the d-band
# oscillators near 2-3 eV absorb blue and green light, and that absorption is their
# colour. A pure Drude model cannot hold it.
HC_EV_NM = _K.h * _K.c / _K.e * 1e9  # h c in eV nm, about 1239.84 (exact SI 2019 constants h, c, e)


def lorentz_drude_eps(wavelength_nm, p):
    """p: {"eps_inf", "plasma_eV", "gamma_eV", "oscillators": [{"strength_eV2", "centre_eV", "width_eV"}]}"""
    e = HC_EV_NM / wavelength_nm
    eps = p["eps_inf"] - p["plasma_eV"] ** 2 / (e * e + 1j * p["gamma_eV"] * e)
    for o in p.get("oscillators", []):
        eps += o["strength_eV2"] / (o["centre_eV"] ** 2 - e * e - 1j * o["width_eV"] * e)
    return eps


def lorentz_drude_nk(wavelength_nm, p):
    N = cmath.sqrt(lorentz_drude_eps(wavelength_nm, p))
    if N.imag < 0:
        N = -N
    return N.real, N.imag
