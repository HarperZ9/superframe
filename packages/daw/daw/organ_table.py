"""The numbers the CLAP organ reads, written from the offline organ (daw/organ.py) so both start from the same bits.

    python -m daw.organ_table           # from packages/daw: rewrites clap/organ_table.h

For each sample rate in RATES, each stop in organ.ORDER and each key from A0 (21) to C8 (108): cos and sin of
the pipe's phase step and its partial count, from the tube that speaks the stop's pitch (organ.pipe_for, with
the Levine-Schwinger end corrections). With them: the open and stopped partial levels, each rank's level and
whether it is stopped, the attack and wind decays per sample, and the release length. Doubles are written as
Python's shortest repr, which parses back to the same double in Python and in C. A fresh derivation on another
machine can differ in the last bit (the platform's cos, sin, exp and pow), which is why the numbers are stored;
tests/test_clap_organ.py holds a fresh derivation within 1e-12.
"""
import sys

from . import PKG
from . import organ as O

RATES = (44100, 48000)
KEYS = range(21, 109)
HEADER = PKG / "clap" / "organ_table.h"


def _d(x):
    return repr(float(x))


def _list(xs):
    return "{" + ", ".join(_d(x) for x in xs) + "}"


def write(path=HEADER):
    ranks = [O.STOPS[s] for s in O.ORDER]
    lines = ["// Generated by daw/organ_table.py from the offline organ; do not edit by hand.",
             "#pragma once", f"#define ORGAN_KEY0 {KEYS[0]}", f"#define ORGAN_KEYS {len(KEYS)}",
             f"#define ORGAN_STOPS {len(ranks)}", f"#define ORGAN_PARTIALS {O.MAX_PARTIALS}",
             f"#define ORGAN_NOISE {O.NOISE!r}", "#define ORGAN_WIND_K 0.04",
             "typedef struct { double c, s; int count; } organ_coef_t;",
             "typedef struct { double attack, wind; int release; organ_coef_t coef[ORGAN_STOPS][ORGAN_KEYS]; } organ_rate_t;",
             f"static const double organ_levels_open[ORGAN_PARTIALS] = {_list(O.levels(False))};",
             f"static const double organ_levels_stopped[ORGAN_PARTIALS] = {_list(O.levels(True))};",
             f"static const double organ_rank_level[ORGAN_STOPS] = {_list(r.level for r in ranks)};",
             "static const int organ_rank_stopped[ORGAN_STOPS] = {" + ", ".join(str(int(r.stopped)) for r in ranks) + "};",
             "// Stops, in bit order: " + "; ".join(O.ORDER)]
    for fs in RATES:
        d = O.live_design(fs)
        lines.append(f"static const organ_rate_t organ_rate_{fs} = {{{_d(d['attack'])}, {_d(d['wind'])}, {d['release']}, {{")
        for si in range(len(ranks)):
            rows = [d["coef"](si, key) for key in KEYS]
            lines.append("    {" + ", ".join(f"{{{_d(c)}, {_d(s)}, {n}}}" for c, s, n in rows) + "},")
        lines.append("}};")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def read(fs, path=HEADER):
    """The header's numbers for one rate, in organ.live_design's shape, parsed back to the same doubles."""
    text = path.read_text(encoding="utf-8")

    def arr(name):
        body = text.split(f"{name}[")[1].split("{")[1].split("}")[0]
        return [float(v) for v in body.split(", ")]
    block = text.split(f"organ_rate_{fs} = {{")[1].split("}};")[0]
    head, body = block.split(", {", 1)
    attack, wind, release = head.split(", ")
    table = []
    for ln in body.strip().splitlines():
        cells = ln.strip().rstrip(",").strip("{}").split("}, {")
        table.append([(float(a), float(b), int(c)) for a, b, c in (x.split(", ") for x in cells)])
    return {"coef": lambda si, key: table[si][key - KEYS[0]], "open": arr("organ_levels_open"),
            "stopped": arr("organ_levels_stopped"), "attack": float(attack), "wind": float(wind),
            "release": int(release)}


if __name__ == "__main__":
    print(write(), file=sys.stderr)
