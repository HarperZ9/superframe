"""The per-note tables the CLAP piano reads, written from the offline code so both use the same numbers.

    python -m daw.clap_tables           # from packages/daw: rewrites clap/piano_table.h

For each sample rate in RATES and each key from A0 (21) to C8 (108): the stiff string's loop as
dispersion.stiff_string builds it (integer delay n, tuning allpass t, loop gain g, dispersion coefficient a and
stage count m, from dispersion.design with B = dispersion.piano_b, the measured Steinway table), and the hammer
force waveguide.hammer(fs, CONTACT). Doubles are written with 17 significant digits, which round-trip exactly,
so the plugin's arithmetic starts from the same bits as the offline render. tests/test_clap.py re-derives
rows and compares them with the header.
"""
import math
import sys

from . import PKG
from . import dispersion as D
from . import waveguide as W

RATES = (44100, 48000)
KEYS = range(21, 109)
T60 = 6.0
CONTACT = 2e-3
HEADER = PKG / "clap" / "piano_table.h"


def f0_of(key):
    return 440.0 * 2.0 ** ((key - 69) / 12)


def row(key, fs):
    f0 = f0_of(key)
    a, m = D.design(f0, fs, D.piano_b(key))
    n, t = D._layout(f0, fs, a, m)
    g = min(10 ** (-3 / (T60 * f0)) / math.cos(math.pi * f0 / fs), 0.99999)
    return n, t, g, a, m


def _d(x):
    return repr(float(x))      # shortest repr: parses back to the same double


def write(path=HEADER):
    lines = ["// Generated by daw/clap_tables.py from the offline code; do not edit by hand.",
             "// Rows: n, t, g, a, m per key from A0 (21) to C8 (108), one table per sample rate.",
             "#pragma once", f"#define PIANO_T60 {T60!r}", f"#define PIANO_KEY0 {KEYS[0]}",
             f"#define PIANO_KEYS {len(KEYS)}", "typedef struct { int n; double t, g, a; int m; } piano_row_t;"]
    for fs in RATES:
        lines.append(f"static const piano_row_t piano_rows_{fs}[PIANO_KEYS] = {{")
        for key in KEYS:
            n, t, g, a, m = row(key, fs)
            lines.append(f"    {{{int(n)}, {_d(t)}, {_d(g)}, {_d(a)}, {int(m)}}},   // key {key}")
            print(fs, key, n, m, flush=True)
        lines.append("};")
        h = W.hammer(fs, CONTACT)
        lines.append(f"static const double piano_hammer_{fs}[{len(h)}] = {{" + ", ".join(repr(float(v)) for v in h) + "};")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


if __name__ == "__main__":
    print(write(), file=sys.stderr)
