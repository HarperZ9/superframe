PRO = """
<h3>Rotations</h3>
<p>A rotation in n dimensions turns one coordinate plane at a time. For axes i and j the matrix is the identity
except for four entries:</p>
<span class="math">R_ij(t): row i = cos t at i, -sin t at j;  row j = sin t at i, cos t at j</span>
<p>There are n(n-1)/2 planes: 1 in 2D, 3 in 3D, 6 in 4D, 10 in 5D. The toy composes them in a fixed order.
The tests compose random angles in every plane for n = 2 to 7 and require |R<sup>T</sup>R - I| and every change
of length to stay under 1e-12. A matrix scaled by 1 + 1e-9 is planted and must fail.</p>

<h3>Projections and what each one costs</h3>
<span class="math">orthographic:   (x1..xn) -> (x1..xk)
perspective:    (x1..xn) -> (d / (d - xn)) (x1..x(n-1)), repeated down to k
stereographic:  S^(n-1) -> R^(n-1),  x -> x(1..n-1) / (1 - xn)</span>
<p>Every view reports one distortion number, the edge spread: over all edges, (longest - shortest) / longest of
the ratio projected length / true length. It is 0 when every edge scales alike (a similarity) and near 1
when some edges collapse. An identity projection must score 0 and the tesseract's 4D to 3D shadow must not
(planted). Stereographic projection is conformal: the tests push pairs of tangent vectors at 50 random points
of S<sup>3</sup> through the map by central differences and require the angle between their images to match
to 1e-6. The same test on the orthographic shadow is planted and must fail (its worst angle error is above
1 radian).</p>

<h3>Cross-sections</h3>
<p>The cutting hyperplane is u &middot; x = s. A slice vertex is a point where an edge crosses it; a slice edge
is where a 2-face crosses it. The volume is exact: the slice's facets are the polytope's facets cut by the
plane, so the volume is a sum of pyramids from the slice's centroid, each of height h over a cut facet of
(n-2)-volume A, contributing h A / (n-1). The tests also run a slower route, the convex hull of the slice points
by recursive pyramids, and compare both with closed forms:</p>
<span class="math">unit n-cube cut by sum x = t:   sqrt(n) / (n-1)!  * sum_k (-1)^k C(n,k) (t-k)^(n-1),  k = 0..floor(t)
corner n-simplex cut by x1 = t: (1-t)^(n-1) / (n-1)!
any n-cube cut across one axis: a unit (n-1)-cube</span>

<h3>Face lattice, f-vectors and Euler</h3>
<p>Nothing is looked up. At each vertex, every choice of n-1 neighbours spans a candidate hyperplane; it is a
facet when every vertex lies on one side and the touching vertices span n-1 dimensions. Each lower level is the
set of pairwise intersections of the level above that span exactly one dimension less, which works because
every face of a polytope sits in exactly two faces one dimension up inside any face two up (the diamond
property). The edges found this way must equal the edges found by shortest distance. The alternating sum
f<sub>0</sub> - f<sub>1</sub> + f<sub>2</sub> - ... equals 1 - (-1)<sup>n</sup>: 0 in 4D, 2 in 3D and 5D.
Planted: a tesseract with 25 squares and a 120-cell with 121 cells.</p>

<h3>Coxeter groups, Petrie polygons and the 120-cell</h3>
<p>Each regular polytope's symmetry group is generated by reflections. The page finds the simple roots without a
table: a positive root is simple exactly when its reflection permutes the other positive roots. The product of
the simple reflections is the Coxeter element; its order is the Coxeter number h, and it turns one plane, the
Coxeter plane, by 2&pi;/h. Projecting onto that plane gives the Petrie polygon picture, whose rotational symmetry the
page measures independently of h. The 120-cell is built as the Wythoff orbit of H<sub>4</sub>, ringed at the
end of the diagram next to the 5, in the same frame as the 600-cell; its published coordinates are kept and
checked congruent by their distance spectrum. The 600-cell's Wythoff orbit equals its published coordinates
point for point.</p>
<p>The brief listed h = 4 for the tesseract. The Coxeter element of B<sub>4</sub> has order 8 and the
tesseract's Petrie polygon is an octagon, so 8 is the value tested and 4 is a planted wrong value the tests
reject. The other values, 12 for the 24-cell and 30 for the 120-cell and 600-cell, agree.</p>

<h3>Fields</h3>
<span class="math">Hopf map:  (z1, z2) -> (2 z1 conj(z2), |z1|^2 - |z2|^2),   S^3 -> S^2
Clifford torus:  |z1| = |z2| = 1/sqrt 2
quaternion Julia:  q -> q^2 + c,   distance bound 0.5 |q| log|q| / |dq|,  dq -> 2 |q| dq</span>
<p>A 3D slice of an n-dimensional signed distance bound is still a bound inside the slice, so sphere tracing
in the slice never steps through a surface. Checked: the 4-ball cut at w = 0.6 is a ball of radius 0.8, and a
traced ray from z = -3 lands at distance 2.2.</p>
"""

