/* diagram/sim/circuit: the circuit record and its compiled form for modified nodal analysis.
   A circuit is a list of elements. Node "0" is ground. Each element is { t, name, n: [nodes], ...params }:
     R  { R, T, noise }          resistor; thermal noise 4kT/R as a current, at its own temperature T (K)
     C  { C }   L { L }          reactive parts (L adds a branch current)
     V  { dc, ac, wave, noiseS } voltage source (adds a branch current); noiseS in V^2/Hz
     I  { dc, ac, wave, noiseS } current source, flowing from n[0] through the source to n[1]; noiseS in A^2/Hz
     D  { Is, N, T }             Shockley diode, anode n[0]; shot noise 2qI at the operating point
     E  { gain, c: [p, m] }      voltage-controlled voltage source
     G  { gm, c: [p, m] }        voltage-controlled current source, n[0] to n[1] through the source
     S  { ron, roff, on, T }     switch: on is a boolean or a function of time; thermal noise of its resistance
     OA { A0, gbw, rin, rout, en, in }  op-amp macro model, n = [in+, in-, out]; expanded into primitives below
   Compilation maps node names to unknowns, gives every V, L and E a branch unknown, and lists the noise sources.
   Nothing here knows about any one instrument. */
(function (g) {
  "use strict";
  const D = (g.Diagram = g.Diagram || {});
  const S = (D.SIM = D.SIM || {});
  /* CODATA 2022, generated by packages/measured; a built page inlines constants.js as globalThis.MeasuredConstants */
  const K = g.MeasuredConstants || require("../../../measured/generated/constants.js");
  S.kB = K.kB; S.q = K.e;

  /* The op-amp macro: input voltage noise in series with in+, input current noise at both inputs, a finite input
     resistance, one gain pole set by A0 and the gain-bandwidth product, a unity buffer and an output resistance.
     Linear: the supplies do not clip it, a limit the report states. */
  S.expandOA = (e) => {
    const A0 = e.A0 || 1e6, gbw = e.gbw || 1e7, gm = 1e-3, Rp = A0 / gm, Cp = 1 / (2 * Math.PI * (gbw / A0) * Rp), N = e.name;
    const [ip, im, out] = e.n, p = N + ".p", x = N + ".x", ro = e.rout === undefined ? 10 : e.rout, o = ro > 0 ? N + ".o" : out;
    const tail = ro > 0 ? [{ t: "R", name: N + ".rout", n: [o, out], R: ro, noise: false, group: N }] : [];
    return [
      { t: "V", name: N + ".en", n: [p, ip], dc: 0, noiseS: (e.en || 0) ** 2, group: N },
      { t: "R", name: N + ".rin", n: [p, im], R: e.rin || 1e12, noise: false, group: N },
      { t: "I", name: N + ".inp", n: [ip, "0"], dc: 0, noiseS: (e.in || 0) ** 2, group: N },
      { t: "I", name: N + ".inm", n: [im, "0"], dc: 0, noiseS: (e.in || 0) ** 2, group: N },
      { t: "G", name: N + ".gm", n: ["0", x], c: [p, im], gm, group: N },
      { t: "R", name: N + ".rp", n: [x, "0"], R: Rp, noise: false, group: N },
      { t: "C", name: N + ".cp", n: [x, "0"], C: Cp, group: N },
      { t: "E", name: N + ".buf", n: [o, "0"], c: [x, "0"], gain: 1, group: N },
    ].concat(tail);
  };

  const BRANCH = new Set(["V", "L", "E"]);
  S.compile = (elements, opt = {}) => {
    const flat = [];
    for (const e of elements) {
      if (!e.name || !e.t || !Array.isArray(e.n)) throw new Error("sim: element needs t, name and n: " + JSON.stringify(e));
      if (e.t === "OA") flat.push(...S.expandOA(e)); else flat.push(Object.assign({ group: e.name }, e));
    }
    const names = new Set(), node = new Map([["0", -1]]);
    const idx = (nm) => { if (!node.has(nm)) node.set(nm, node.size - 1); return node.get(nm); };
    for (const e of flat) {
      if (names.has(e.name)) throw new Error("sim: duplicate element name " + e.name);
      names.add(e.name);
      e.i = e.n.map(idx);
      if (e.c) e.ci = e.c.map(idx);
    }
    const nN = node.size - 1;
    let nb = 0;
    for (const e of flat) if (BRANCH.has(e.t)) e.br = nN + nb++;
    const T0 = opt.T || 300;
    const noise = [];
    for (const e of flat) {
      if (e.t === "R" && e.noise !== false) noise.push({ el: e, kind: "i", S: () => 4 * S.kB * (e.T || T0) / e.R });
      if (e.t === "S") noise.push({ el: e, kind: "i", S: (op) => 4 * S.kB * (e.T || T0) / S.switchR(e, op ? op.t : 0) });
      if ((e.t === "I") && e.noiseS) noise.push({ el: e, kind: "i", S: () => e.noiseS });
      if (e.t === "V" && e.noiseS) noise.push({ el: e, kind: "v", S: () => e.noiseS });
      if (e.t === "D") noise.push({ el: e, kind: "i", S: (op) => 2 * S.q * Math.abs(S.diodeI(e, op.x)[0]) });
    }
    return { elements: flat, node, nN, size: nN + nb, noise, T: T0, nonlinear: flat.some((e) => e.t === "D"), timeVarying: flat.some((e) => e.t === "S" && typeof e.on === "function") };
  };

  S.switchR = (e, t) => ((typeof e.on === "function" ? e.on(t) : e.on) ? e.ron || 0.1 : e.roff || 1e12);

  /* diode current and conductance at the present node voltages */
  S.diodeI = (e, x) => {
    const va = e.i[0] < 0 ? 0 : x[e.i[0]], vb = e.i[1] < 0 ? 0 : x[e.i[1]], Vt = S.kB * (e.T || 300) / S.q * (e.N || 1), Is = e.Is || 1e-14;
    const v = Math.min(va - vb, 40 * Vt), ex = Math.exp(v / Vt);
    return [Is * (ex - 1), (Is * ex) / Vt, v];
  };

  /* Source value at time t: dc, then a step, pulse, sine or a function. */
  S.srcValue = (e, t) => {
    const w = e.wave;
    if (!w) return e.dc || 0;
    if (typeof w === "function") return w(t);
    if (w.type === "step") { if (t < (w.t0 || 0)) return w.v0 || 0; const r = w.rise || 0; return r > 0 && t < w.t0 + r ? w.v0 + (w.v1 - w.v0) * (t - w.t0) / r : w.v1; }
    if (w.type === "sin") return (w.vo || 0) + w.va * Math.sin(2 * Math.PI * w.f * (t - (w.td || 0)) + (w.ph || 0));
    if (w.type === "pulse") { const tt = (t - (w.td || 0)) % w.per; return t < (w.td || 0) ? w.v0 : tt < w.width ? w.v1 : w.v0; }
    throw new Error("sim: unknown wave " + w.type);
  };

  S.nodeIndex = (ck, name) => { if (!ck.node.has(name)) throw new Error("sim: no node " + name); return ck.node.get(name); };

  if (typeof module !== "undefined" && module.exports) module.exports = S;
})(typeof globalThis !== "undefined" ? globalThis : this);
