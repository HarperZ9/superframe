// Writes combat's frame data in the character lead's timing schema (characters/anim/timing.json:
// 30 frames a second; startup, active, recovery counts; iframes [from, to); cancel as frames into
// recovery; move in metres; hit reach and arc), so the art reads combat's numbers instead of
// keeping its own. Output: out/timing.combat.json (this folder). Run: node tools/export-timing.mjs
import { writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { defineMoves, rootSpeed, FPS } from "../sim/moves.mjs";
import { COMMON } from "../data/common.mjs";
import { BODY } from "../data/body.mjs";
import { SPECIALS, ARCHETYPES } from "../data/foes.mjs";
import { TOOLS, profileOf, buildToolMoves } from "../data/tools.mjs";

const OUT_FPS = 30, k = OUT_FPS / FPS, fr = (n) => Math.round(n * k);
const here = dirname(fileURLToPath(import.meta.url));

function entry(m) {
  const e = { startup: fr(m.startup), active: fr(m.active), recovery: fr(m.recovery), frames60: [m.startup, m.active, m.recovery] };
  if (m.iframes) e.iframes = [fr(m.iframes[0]), fr(m.iframes[1] + 1)];
  const c = Object.values(m.cancel).map((w) => w[0]).sort((a, b) => a - b)[0];
  if (c != null) e.cancel = Math.max(0, fr(c - m.startup - m.active));
  let move = 0; for (let f = 0; f < m.total; f++) move += rootSpeed(m, f) / FPS;
  if (move) e.move = +move.toFixed(2);
  if (m.hits.length) e.hit = { reach: m.hits[0].r[1], arc: m.hits[0].arc[1] - m.hits[0].arc[0] };
  if (m.tell) e.tell = [fr(m.tell.at[0]), fr(m.tell.at[1])];
  if (m.charge) e.charge = { at: fr(m.charge.at), min: fr(m.charge.min), max: fr(m.charge.max) };
  return e;
}

// Clip names: tool strikes as <class>.<strike>; dodges get _f/_b/_l/_r in play (anim/drive.mjs).
function table(moves) {
  const M = defineMoves(moves), out = {};
  for (const m of Object.values(M)) out[m.anim] = entry(m);
  return out;
}

const classes = [...new Set(Object.values(TOOLS).map((t) => t.cls))];
const lamb = { ...COMMON, ...BODY };
for (const cls of classes) Object.assign(lamb, buildToolMoves(profileOf(Object.keys(TOOLS).find((id) => TOOLS[id].cls === cls)), { prefix: `${cls}:` }));
const doc = {
  _about: "Generated by game/engine/combat/tools/export-timing.mjs from combat's move data. 30 frames a second (frames60 keeps the source counts). Combat is authoritative; clips are warped to these phases at play (anim/drive.mjs). Do not edit by hand.",
  fps: OUT_FPS, lamb: table(lamb),
};
for (const [style, A] of Object.entries(ARCHETYPES)) {
  const t = { ...COMMON, ...BODY, ...buildToolMoves(profileOf(A.defaults.tool)) };
  for (const s of A.specials) t[s] = SPECIALS[s];
  doc[style] = table(t);
}
mkdirSync(join(here, "..", "out"), { recursive: true });
writeFileSync(join(here, "..", "out", "timing.combat.json"), JSON.stringify(doc, null, 1));
console.log("clips:", Object.fromEntries(Object.entries(doc).filter(([k2]) => !k2.startsWith("_") && k2 !== "fps").map(([a, t]) => [a, Object.keys(t).length])));
